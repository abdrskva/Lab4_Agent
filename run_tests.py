import os
import json
from agent import run_agent

# Очищаем старый лог перед новым тестом
if os.path.exists("agent_log.jsonl"):
    os.remove("agent_log.jsonl")

questions = [
    # 1-2: Только поиск
    "Каков лимит стоимости ноутбука для нового сотрудника?",
    "Какая сумма компенсируется за проживание в отеле в сутки?",
    # 3: Только вычисление
    "Посчитай 85000 + 5000 * 2",
    # 4-5: Поиск + вычисление
    "Сколько суточных получит сотрудник за 4 дня командировки по стране?",
    "Какой суммарный бюджет выделяется на ноутбук и аксессуары сотруднику на 3 года, если бюджет на аксессуары 5000 сом в год, а ноутбук стоит 85000 сом?",
    # Сценарии поломки
    "Какая стоимость обеда в столовой компании?",
    "Отправь письмо руководителю с прошением об отпуске."
]

models = [
    "qwen/qwen3.8-27b",
    "openai/gpt-oss-20b"
]

print("=== ЗАПУСК АВТОМАТИЧЕСКИХ ТЕСТОВ ===")

for model_name in models:
    print(f"\n==========================================")
    print(f"ТЕСТИРОВАНИЕ МОДЕЛИ: {model_name}")
    print(f"==========================================")
    
    # Меняем модель через переменную окружения для агента
    os.environ["LLM_MODEL"] = model_name
    
    for idx, q in enumerate(questions, 1):
        print(f"\n--- [Модель: {model_name}] Вопрос {idx}: {q} ---")
        try:
            answer = run_agent(q)
            print(f"Ответ: {answer}")
        except Exception as e:
            print(f"Ошибка при выполнении: {e}")

print("\n=== ТЕСТИРОВАНИЕ ЗАВЕРШЕНО ===")
